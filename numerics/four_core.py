# Adapted from robustness-review-v75/code; adopted for manuscript reproduction on 2026-10-12.
"""Standalone, four-qubit robustness audit primitives.

Coordinates are c_a(A)=Tr(A T_a), ordered lexicographically with I,X,Y,Z
digits 0,1,2,3.  Every pool vector has c_0=1.  Robustness is
min sum |p_j| with A p=c(rho), equivalently max c(rho).y with |A.T y|<=1.

The max-weight seed is gamma(u)=sum_{i<j} ((u_i*u_j) mod 3) mod 2,
with X,Y,Z identified with 0,1,2.  Its proper local-Clifford orbit is
generated by signed permutations of X,Y,Z of determinant +1.  For n=4
the Bell orbit is the disjoint union of this orbit and its full-correlation
negation; identity coordinates stay +1, so this is NOT negating operators.

Exact symmetry reduction: rho=T^4 H_U |G><G| H_U (T.dagger)^4 is fixed by
the 16-element group conjugating the graph stabilizers by T^4 H_U. Each
generator is a tensor product of Z and R=(X+Y)/sqrt(2), both Cliffords.
Conjugation by R swaps X,Y and negates Z. D,S and each orbit are invariant
under these conjugations. Averaging a feasible dual over this group is
therefore lossless. W below spans the invariant dual vectors, y=W.T z.
Its disjoint signed rows give the exact twirl P=W.T diag(1/row_norms) W.
The reduced LP uses W A and W c(rho). A reduced primal decomposition lifts
to a physical-coordinate decomposition by twirling every selected original
pool vector. A twirled vector is a convex average of allowed pool vectors.
This proves both directions of equivalence; numerical certificates are
also checked against every ORIGINAL pool vector, not just reduced columns.
"""

import hashlib
import itertools
import math

import numpy as np
from scipy import sparse
from scipy.optimize import linprog

N = 4



def catalogue():
    """Manuscript independent-set catalogue (v74/v75); one-based labels."""
    groups = [
        ("G3", [(1,4),(2,4),(3,4)], [[],[1],[4],[1,2],[1,2,3]]),
        ("P4", [(1,3),(1,4),(2,4)], [[],[1],[2],[1,2],[2,3]]),
        ("G2", [(1,3),(1,4),(2,4),(3,4)], [[],[1],[2],[4],[1,2]]),
        ("C4", [(1,3),(1,4),(2,3),(2,4)], [[],[1],[1,2]]),
        ("G1", [(1,3),(1,4),(2,3),(2,4),(3,4)], [[],[1],[3],[1,2]]),
        ("K4", list(itertools.combinations(range(1,5),2)), [[],[1]]),
    ]
    result=[]
    for graph,edges,decorations in groups:
        for U in decorations:
            result.append({"index":len(result)+1,"graph":graph,"edges":[list(e) for e in edges],"U":U})
    return result


def pauli_data():
    digits=np.array(list(itertools.product(range(4),repeat=N)),dtype=np.int8)
    comm=np.zeros((4**N,4**N),dtype=np.uint8)
    phase=np.zeros_like(comm)
    local=np.array([[0,0,0,0],[0,0,1,3],[0,3,0,1],[0,1,3,0]])
    for j in range(N):
        a,b=digits[:,None,j],digits[None,:,j]
        comm^=((a!=b)&(a!=0)&(b!=0)).astype(np.uint8)
        phase=(phase+local[a,b])%4
    return digits,comm,phase


def isotropic_spaces(comm):
    levels=[{(0,):()}]
    for _ in range(N):
        nxt={}
        for I,basis in levels[-1].items():
            candidates=np.flatnonzero(~np.any(comm[list(basis)],axis=0)) if basis else range(4**N)
            for a in candidates:
                if a in I:
                    continue
                J=tuple(sorted(I+tuple(int(a)^b for b in I)))
                if J not in nxt:
                    nxt[J]=basis+(int(a),)
        levels.append(nxt)
    assert [len(x) for x in levels]==[1,255,5355,11475,2295]
    return levels


def stabilizer_pool(levels,phase):
    rows=[];cols=[];vals=[];column=0
    for _,basis in levels[N].items():
        for gen in itertools.product([1,-1],repeat=N):
            signs={0:1}
            for a,t in zip(basis,gen):
                signs.update({a^b:int(s*t*(1 if phase[a,b]==0 else -1)) for b,s in list(signs.items())})
            rows.extend(signs);cols.extend([column]*len(signs));vals.extend(signs.values())
            column+=1
    assert column==36720
    return sparse.csc_matrix((vals,(rows,cols)),shape=(4**N,column),dtype=float)


def deterministic_pool():
    local=np.array([[1,*s] for s in itertools.product([1,-1],repeat=3)])
    result=local.T
    for _ in range(N-1):
        result=np.kron(result,local.T)
    return sparse.csc_matrix(result,dtype=float)


def clifford_orbit(digits):
    full=np.flatnonzero(np.all(digits!=0,axis=1));inputs=digits[full]-1
    perms=list(itertools.permutations(range(3)))
    parity={p:(-1)**sum(p[i]>p[j] for i in range(3) for j in range(i+1,3)) for p in perms}
    flips=np.array([[1,*s] for s in itertools.product([1,-1],repeat=2)],dtype=np.int8)
    tuples=np.array(list(itertools.product(flips,repeat=N)),dtype=np.int8)
    flipvals=np.prod(tuples[:,np.arange(N)[None,:],inputs],axis=2).astype(np.int8)
    flipparity=np.prod(tuples[:,:,1:],axis=(1,2)).astype(np.int8)
    signs=set()
    for ps in itertools.product(perms,repeat=N):
        u=np.array(ps)[np.arange(N)[None,:],inputs]
        gamma=np.zeros(len(inputs),dtype=int)
        for i in range(N):
            for j in range(i+1,N):
                gamma+=(u[:,i]*u[:,j])%3
        v=(1-2*(gamma%2)).astype(np.int8)
        # Canonical local signs h=(1,h1,h2). Multiplying each by
        # t=parity(permutation)*h1*h2 enforces determinant +1 locally.
        orientation=math.prod(parity[p] for p in ps)
        images=flipvals*v[None,:]*(flipparity*orientation)[:,None]
        signs.update(row.tobytes() for row in images)
    assert len(signs)==165888
    assert all((-np.frombuffer(w,dtype=np.int8)).tobytes() not in signs for w in signs)
    result=np.array([np.frombuffer(w,dtype=np.int8) for w in sorted(signs)],dtype=np.int8)
    return full,result


def pool_hash(A):
    if sparse.issparse(A):
        A=A.tocsc();h=hashlib.sha256()
        for x in (np.asarray(A.shape,dtype='<i8'),A.indptr.astype('<i8'),A.indices.astype('<i8'),A.data.astype(np.int8)):
            h.update(x.tobytes())
        return h.hexdigest()
    return hashlib.sha256(np.asarray(A,dtype=np.int8).tobytes()).hexdigest()


def build_pools():
    digits,comm,phase=pauli_data()
    D=deterministic_pool();S=stabilizer_pool(isotropic_spaces(comm),phase)
    full,signs=clifford_orbit(digits)
    hashes={"D":pool_hash(D),"S":pool_hash(S),"M_clifford_fullweight_signs":pool_hash(signs)}
    return {"digits":digits,"D":D,"S":S,"full":full,"M":signs.astype(float),"hashes":hashes}


def resource(case,digits):
    bits=np.array(list(itertools.product(range(2),repeat=N)))
    ket=np.ones(2**N,dtype=complex)/math.sqrt(2**N)
    for i,j in case["edges"]:
        ket*=(-1.)**(bits[:,i-1]*bits[:,j-1])
    H=np.array([[1,1],[1,-1]])/math.sqrt(2)
    for i in case["U"]:
        gate=np.eye(1)
        for j in range(1,N+1):
            gate=np.kron(gate,H if i==j else np.eye(2))
        ket=gate@ket
    ket*=np.exp(1j*np.pi/4*np.sum(bits,axis=1))
    ps=[np.eye(2),np.array([[0,1],[1,0]]),np.array([[0,-1j],[1j,0]]),np.diag([1,-1])]
    values=[]
    for ds in digits:
        P=np.eye(1)
        for d in ds:
            P=np.kron(P,ps[d])
        values.append(np.vdot(ket,P@ket).real)
    return np.array(values)


def twirl_basis(case,digits):
    edges=[(a-1,b-1) for a,b in case["edges"]];U=[i-1 for i in case["U"]]
    generators=[]
    for i in range(N):
        types=np.zeros(N,dtype=np.int8);types[i]=1
        for a,b in edges:
            if a==i:types[b]=3
            if b==i:types[a]=3
        for j in U:
            if types[j]==1:types[j]=3
            elif types[j]==3:types[j]=1
        ds=digits.copy();sgn=np.ones(4**N,dtype=np.int8)
        for j,typ in enumerate(types):
            if typ==1:
                sgn*=np.where(digits[:,j]==3,-1,1)
                ds[:,j]=np.where(digits[:,j]==1,2,np.where(digits[:,j]==2,1,digits[:,j]))
            elif typ==3:
                sgn*=np.where((digits[:,j]==1)|(digits[:,j]==2),-1,1)
        indices=ds@np.array([4**k for k in range(N-1,-1,-1)])
        generators.append((indices,sgn))
    seen=set();rows=[]
    for a in range(4**N):
        if a in seen:continue
        orientation={a:1};queue=[a];inconsistent=False
        for x in queue:
            for ix,sgn in generators:
                b=int(ix[x]);v=orientation[x]*int(sgn[x])
                if b in orientation:
                    if orientation[b]!=v:inconsistent=True
                else:
                    orientation[b]=v;queue.append(b)
        seen.update(orientation)
        if not inconsistent:
            row=np.zeros(4**N,dtype=np.int8)
            for b,v in orientation.items():row[b]=v
            rows.append(row)
    W=np.array(rows,dtype=float)
    assert W.shape==(16,256)
    assert np.array_equal(W@W.T,np.diag(np.sum(W*W,axis=1)))
    return W,generators


def project(W,vector):
    return W.T@((W@vector)/np.sum(W*W,axis=1))


def compress(values,family):
    unique,indices=np.unique(np.asarray(values,dtype=np.int16).T,axis=0,return_index=True)
    families=np.full(len(indices),family,dtype=np.int8)
    return sparse.csc_matrix(unique.T,dtype=float),families,indices.astype(np.int64)


def reduced_pools(pools,W,orbits):
    result={"D":compress((sparse.csc_matrix(W)@pools["D"]).toarray(),0),"S":compress((sparse.csc_matrix(W)@pools["S"]).toarray(),1)}
    correlations=W[:,pools["full"]]@pools["M"].T
    if "clifford" in orbits:
        result["clifford"]=compress(W[:,[0]]+correlations,2)
    if "bell" in orbits:
        matrix,families,indices=compress(np.concatenate([W[:,[0]]+correlations,W[:,[0]]-correlations],axis=1),2)
        negative=indices>=len(pools["M"]);families[negative]=3;indices[negative]-=len(pools["M"])
        result["bell"]=(matrix,families,indices)
    return result


def original_seeds(pools,families,indices):
    columns=[]
    for family,index in zip(families,indices):
        if family in (0,1):
            v=pools["D" if family==0 else "S"][:,int(index)].toarray().ravel()
        else:
            v=np.zeros(4**N);v[0]=1
            v[pools["full"]]=pools["M"][int(index)]*(1 if family==2 else -1)
        columns.append(v)
    return np.array(columns).T


def full_dual_violation(pools,dual,kind,orbit):
    bounds=[]
    if kind == "D":
        bounds.append(np.max(np.abs(pools["D"].T@dual))-1)
    if kind in ("L1","L2"):
        bounds.extend([np.max(np.abs(pools["D"].T@dual))-1,np.max(np.abs(dual[0]+pools["M"]@dual[pools["full"]]))-1])
        if orbit=="bell":bounds.append(np.max(np.abs(dual[0]-pools["M"]@dual[pools["full"]]))-1)
    if kind in ("S","L2"):
        bounds.append(np.max(np.abs(pools["S"].T@dual))-1)
    return float(max(0,max(bounds)))


def solve(pools,reduced,W,rho,kind,orbit):
    names=[kind] if kind in ("S","D") else (["S","D",orbit] if kind=="L2" else ["D",orbit])
    A=sparse.hstack([reduced[name][0] for name in names]).tocsc()
    families=np.concatenate([reduced[name][1] for name in names]);indices=np.concatenate([reduced[name][2] for name in names])
    target=W@rho
    lp=linprog(-target,A_ub=sparse.vstack([A.T,-A.T]),b_ub=np.ones(2*A.shape[1]),bounds=[(None,None)]*16,method="highs",options={"dual_feasibility_tolerance":1e-9,"primal_feasibility_tolerance":1e-9})
    if not lp.success:raise RuntimeError(lp.message)
    multipliers=-lp.ineqlin.marginals
    p=multipliers[:A.shape[1]]-multipliers[A.shape[1]:]
    selected=np.flatnonzero(np.abs(p)>1e-11)
    p=p[selected];families=families[selected];indices=indices[selected]
    seeds=original_seeds(pools,families,indices)
    dual=W.T@lp.x
    value=float(rho@dual);primal_l1=float(np.abs(p).sum())
    result={"kind":kind,"orbit":orbit,"value":value,"primal_l1":primal_l1,"primal_residual":float(np.max(np.abs(project(W,seeds@p)-rho))),"dual_violation":full_dual_violation(pools,dual,kind,orbit),"gap":abs(value-primal_l1),"support_size":len(p),"reduced_columns":A.shape[1]}
    assert max(result["primal_residual"],result["dual_violation"],result["gap"])<1e-8,result
    certificate={"W":W,"rho":rho,"weights":p,"families":families,"pool_indices":indices,"seeds":seeds,"dual":dual}
    return result,certificate
