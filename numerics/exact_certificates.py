def resource_description(case):
    return {"n": case["n"], "graph": case["graph"],
            "edges_zero_based": case["edges"], "U_zero_based": case["U"],
            "formula": "T^tensor(n) H^tensor(U) |G>"}


def family_for(column, counts):
    if column < counts["C"]:
        return "C"
    if column < counts["C"] + counts["D"]:
        return "D"
    return "M"


def exact_optimality_certificate(case, matrix, numeric, exact_target, counts, pool="L3"):
    support = np.flatnonzero(np.abs(numeric.primal) > 1e-8)
    integer_columns = matrix[:, support].toarray().astype(np.int64)
    weights = exact_primal_weights(integer_columns, 1, exact_target)
    norm = sp.simplify(sum(pair_sign(qpair(w))*w for w in weights))
    assert sp.simplify(sum(weights)) == 1
    dual = rational_dual_certificate(matrix, numeric.dual, exact_target)
    assert encode_qpair(norm) == dual["objective"]
    return {
        "kind": "exact_primal_and_dual_optimality",
        "resource": resource_description(case),
        "phase_space": ("C union D union M (proper local-Clifford orbit)"
                        if pool == "L3" else "C"),
        "dual_constraint_pool": pool,
        "target_coordinates": [encode_qpair(x) for x in exact_target],
        "primal_terms": [
            {"family": family_for(int(j), counts) if pool == "L3" else "C",
             "weight": encode_qpair(w), "weight_expression": str(w),
             "pauli_coefficients": integer_columns[:, k].tolist()}
            for k, (j, w) in enumerate(zip(support, weights))
        ],
        "norm": encode_qpair(norm), "norm_expression": str(norm),
        "norm_decimal": float(norm), "dual": dual,
        "floating_point_diagnostics": numeric.summary(),
    }


def c_union_d_certificate(case, digits, spaces, counts, exact_target):
    matrix = sparse.hstack([spaces["C"], spaces["D"]]).tocsc()
    twirl_sum, twirl_size = graph_state_twirl(3, case["edges"], digits)
    integer_twirl_columns = (sparse.csc_matrix(twirl_sum) @ matrix).tocsc()
    averaged = integer_twirl_columns.astype(float) / twirl_size
    target = np.array([float(x) for x in exact_target])
    numeric = solve_robustness(averaged, target)
    support = np.flatnonzero(np.abs(numeric.primal) > 1e-8)
    weights = exact_primal_weights(
        integer_twirl_columns[:, support].toarray().astype(np.int64),
        twirl_size, exact_target)
    norm = sp.simplify(sum(pair_sign(qpair(w))*w for w in weights))
    assert sp.simplify(sum(weights)) == 1
    assert norm < 1 + sp.sqrt(2)/5
    return {
        "kind": "exact_feasible_upper_bound_independent_of_M",
        "resource": resource_description(case), "phase_space": "C union D",
        "target_coordinates": [encode_qpair(x) for x in exact_target],
        "twirl": {
            "definition": "Average conjugation by the group generated by "
                          "g_i=((X+Y)/sqrt(2))_i product_(j in N(i)) Z_j, "
                          "together with all graph automorphisms.",
            "number_of_group_elements": twirl_size,
            "admissibility": "All group elements are local Cliffords and/or "
                             "qubit permutations, so each averaged C or D seed "
                             "is a convex combination of operators in the same family.",
        },
        "primal_terms": [
            {"family": family_for(int(j), counts),
             "weight": encode_qpair(w), "weight_expression": str(w),
             "seed_pauli_coefficients": matrix[:, int(j)].toarray().ravel().astype(int).tolist()}
            for j, w in zip(support, weights)
        ],
        "norm": encode_qpair(norm), "norm_expression": str(norm),
        "norm_decimal": float(norm),
        "comparison_CNC_value": "1 + sqrt(2)/5",
        "qualification": "This certificate proves a feasible upper bound. "
                         "Optimality of C union D is not needed or asserted.",
        "floating_point_diagnostics": numeric.summary(),
    }


def check_family(column, family, digits, comm, phase, m_members):
    assert column.shape == (64,)
    assert column[0] == 1 and set(column).issubset({-1, 0, 1})
    if family == "C":
        assert validate_cnc_column(column, comm, phase), "Invalid CNC seed"
    elif family == "D":
        assert validate_deterministic_column(column, digits), "Invalid deterministic seed"
    elif family == "M":
        assert column.astype(np.int8).tobytes() in m_members, "Seed outside the actual Clifford orbit"
    else:
        raise AssertionError(f"Unknown family: {family}")


def verify_one(certificate, digits, comm, phase, spaces, m_members):
    description = certificate["resource"]
    target = exact_resource_coordinates(3, description["edges_zero_based"],
                                        description["U_zero_based"], digits)
    target_pairs = [qpair(x) for x in target]
    assert target_pairs == [decode_qpair(x) for x in certificate["target_coordinates"]]
    reconstructed = [[Fraction(0), Fraction(0)] for _ in range(64)]
    norm, total_weight = [Fraction(0), Fraction(0)], [Fraction(0), Fraction(0)]
    is_twirl = "twirl" in certificate
    if is_twirl:
        twirl_sum, size = graph_state_twirl(3, description["edges_zero_based"], digits)
        assert size == certificate["twirl"]["number_of_group_elements"]
        assert sp.Matrix(twirl_sum.tolist()) * target == size * target
    for term in certificate["primal_terms"]:
        key = "seed_pauli_coefficients" if is_twirl else "pauli_coefficients"
        column = np.array(term[key], dtype=np.int64)
        check_family(column, term["family"], digits, comm, phase, m_members)
        if is_twirl:
            column, denominator = twirl_sum @ column, size
        else:
            denominator = 1
        pair = decode_qpair(term["weight"])
        sign = pair_sign(pair)
        for k in (0, 1):
            norm[k] += sign * pair[k]
            total_weight[k] += pair[k]
        for i, value in enumerate(column):
            for k in (0, 1):
                reconstructed[i][k] += Fraction(int(value), denominator) * pair[k]
    assert [tuple(row) for row in reconstructed] == target_pairs
    assert total_weight == [Fraction(1), Fraction(0)]
    assert tuple(norm) == decode_qpair(certificate["norm"])
    if "dual" in certificate:
        dual = certificate["dual"]
        pool = certificate["dual_constraint_pool"]
        assert pool in ("C", "L3")
        maximum = max_integer_dual_constraint(spaces[pool], dual["numerators"])
        assert maximum <= dual["denominator"]
        assert maximum == dual["maximum_absolute_constraint_numerator"]
        dual_value = tuple(sum(Fraction(y, dual["denominator"])*target_pairs[i][k]
                               for i, y in enumerate(dual["numerators"]))
                           for k in (0, 1))
        assert dual_value == tuple(norm) == decode_qpair(dual["objective"])
    return {"exact_target_match": True, "all_seed_memberships_valid": True,
            "exact_reconstruction": True, "exact_sum_weights_one": True,
            "exact_norm_match": True,
            "exact_dual_feasible_and_equal": "dual" in certificate,
            "primal_seed_count": len(certificate["primal_terms"])}


